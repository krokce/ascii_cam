#!/usr/bin/env python3
"""Convert the printable ASCII glyphs of an 8 by 14 PSF1 console font
into the C source file src/font_data.c used by the camera program.

The appliance uses Terminus Font 8x14 (SIL Open Font License 1.1), from
the file Uni2-Terminus14.psf.gz of the console-setup package. Each glyph
becomes 14 rows of 8 bits; the program adds a blank ninth column, the
way an MDA card spaces characters. Block and line glyphs are not taken
from the font: the program draws them itself.

Usage: psf2c.py /usr/share/consolefonts/Uni2-Terminus14.psf.gz src/font_data.c
"""
import gzip
import sys


def load_psf1(path):
    data = gzip.open(path, "rb").read() if path.endswith(".gz") else open(path, "rb").read()
    if data[0:2] != b"\x36\x04":
        raise SystemExit("not a PSF1 font")
    mode, height = data[2], data[3]
    count = 512 if mode & 1 else 256
    glyphs = [data[4 + i * height: 4 + (i + 1) * height] for i in range(count)]
    table = {}
    if mode & 2:  # Unicode table: per glyph, UCS-2 values ending in 0xFFFF
        pos = 4 + count * height
        for g in range(count):
            while pos + 1 < len(data):
                v = data[pos] | (data[pos + 1] << 8)
                pos += 2
                if v == 0xFFFF:
                    break
                if v == 0xFFFE:
                    continue
                table.setdefault(v, g)
    return height, glyphs, table


def main():
    height, glyphs, table = load_psf1(sys.argv[1])
    if height != 14:
        raise SystemExit("font must be 14 rows high")
    out = []
    out.append("/* Generated by tools/psf2c.py from Terminus Font 8x14.")
    out.append(" * Copyright (c) 2010 Dimitar Toshkov Zhekov.")
    out.append(" * Licensed under the SIL Open Font License, Version 1.1;")
    out.append(" * see FONT-LICENSE.txt. This is a modified version (converted,")
    out.append(" * with a ninth blank column added at run time) and is not")
    out.append(" * itself named Terminus Font. */")
    out.append("#include \"font.h\"")
    out.append("")
    out.append("const unsigned char font_ascii[95][14] = {")
    for code in range(32, 127):
        g = glyphs[table.get(code, code)]
        rows = ", ".join("0x%02x" % b for b in g)
        ch = chr(code)
        label = {"\\": "backslash", "*": "star"}.get(ch, ch)
        out.append("\t{ %s }, /* %s */" % (rows, label))
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
